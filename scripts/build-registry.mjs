// ── checks ──────────────────────────────────────────────────────────────────
const ids = ENTRIES.map((e) => e[0]);
const dupes = ids.filter((id, i) => ids.indexOf(id) !== i);
if (dupes.length) throw new Error(`duplicate ids: ${[...new Set(dupes)].join(', ')}`);

const badCategory = ENTRIES.filter((e) => !CATEGORIES.has(e[2]));
if (badCategory.length) throw new Error(`bad category: ${badCategory.map((e) => e[0]).join(', ')}`);

const badId = ids.filter((id) => !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(id));
if (badId.length) throw new Error(`ids must be kebab-case: ${badId.join(', ')}`);

const MINIMUM = 250;
if (ENTRIES.length < MINIMUM) {
  throw new Error(`registry holds ${ENTRIES.length} entries, ${MINIMUM} required`);
}

// ── batching ────────────────────────────────────────────────────────────────
// Batches are the unit of work handed to one writing agent. The number is chosen from
// the other end: a slice of ~22 entries is small enough that an agent writes each file
// deliberately instead of racing a quota, which is the failure mode that would leave us
// with 352 thin files instead of 352 usable ones.
const BATCHES = 16;
const perBatch = Math.ceil(ENTRIES.length / BATCHES);

const entries = ENTRIES.map(([id, title, category, tradition, philosophers, era], i) => ({
  id,
  title,
  category,
  tradition,
  philosophers: philosophers.split('|'),
  era,
  batch: Math.floor(i / perBatch) + 1,
}));

const philosopherCount = new Set(entries.flatMap((e) => e.philosophers)).size;

const registry = {
  generatedBy: 'scripts/build-registry.mjs',
  count: entries.length,
  philosophers: philosopherCount,
  categories: Object.fromEntries(
    [...CATEGORIES].map((c) => [c, entries.filter((e) => e.category === c).length]),
  ),
  batches: BATCHES,
  perBatch,
  entries,
};

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'theories', '_registry.json');
writeFileSync(out, `${JSON.stringify(registry, null, 2)}\n`);

console.log(`${entries.length} entries · ${philosopherCount} named thinkers · ${BATCHES} batches of ≤${perBatch}`);
