export const PHILOSOPHERS = ROWS.map(([id, name, era, role, weights, voice]) => {
  const vector = {};
  for (const token of weights.split(/\s+/).filter(Boolean)) {
    const match = token.match(/^([A-Za-z]{3})(-?[\d.]+)$/);
    if (!match) throw new Error(`${id}: cannot parse weight "${token}"`);
    const [, code, value] = match;
    const axis = FRAMEWORK[code] ?? DISPOSITION[code];
    if (!axis) throw new Error(`${id}: unknown axis code "${code}"`);
    vector[axis] = Number(value);
  }
  return { id, name, era, role, voice, vector };
});

export const AXIS_CODES = { FRAMEWORK, DISPOSITION };
