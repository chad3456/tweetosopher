export const GLOSSARY = ROWS.map(([id, name, category, source, definition, example, status]) => {
  if (!CATEGORIES.has(category) && category !== 'theory' && category !== 'contested') {
    throw new Error(`${id}: unknown category "${category}"`);
  }
  if (!STATUSES.has(status)) throw new Error(`${id}: unknown status "${status}"`);
  return { id, name, category: category === 'contested' ? 'effect' : category, source, definition, example, status };
});

export const GLOSSARY_STATUS = {
  robust: 'Replicated repeatedly, including by people who wanted it to fail.',
  mixed: 'Real, but smaller, narrower or more conditional than popularly told.',
  contested: 'Serious specialists actively disagree about whether it holds.',
  failed: 'Large or pre-registered replications did not find it.',
  '—': 'Not an empirical claim: a principle, a law or a definition.',
};
